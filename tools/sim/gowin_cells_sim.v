// Gowin primitives needed by the simulation build, extracted verbatim from
// oss-cad-suite's share/yosys/gowin/ with `specify` blocks removed (Verilator
// rejects them).  Only the three cells GBATang's generated IP still instantiates
// under VERILATOR are included, because mem_eeprom.v uses MUX2, DFFRE and DPB:
//   MUX2 and DFFRE from cells_sim.v, DPB from cells_xtra_gw5a.v (the GW5A
//   variant, i.e. the device this port targets).
//
// MUX2 is also supplied behaviourally by tools/cells_behavioral.v for the
// synthesis build; that file is not used by the simulation.
//
// This is a simulation shim, not vendored IP.  The definitions are the vendor's
// published simulation semantics, reproduced so the sim models the same
// primitives the bitstream is packed against.
//
module MUX2 (O, I0, I1, S0);
  input I0,I1;
  input S0;
  output O;


  assign O = S0 ? I1 : I0;
endmodule

module DFFRE (output reg Q, input D, CLK, CE, RESET);
  parameter [0:0] INIT = 1'b0;
  initial Q = INIT;


  always @(posedge CLK) begin
    if (RESET)
      Q <= 1'b0;
    else if (CE)
      Q <= D;
  end
endmodule // DFFRE (positive clock edge; synchronous reset takes precedence over clock enable)

