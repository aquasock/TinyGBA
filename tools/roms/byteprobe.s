@ Eleven byte loads from cartridge ROM, compared against the image, then
@ ten more with an odd base address and unaligned offsets, which is how font
@ data is actually read.  One 16x16 square each: green pass, red fail.
_start:
    ldr     r11, =0x04000000
    mov     r0, #0
    strh    r0, [r11]
    ldr     r0, =0x0403
    strh    r0, [r11]

    ldr     r9, =0x06000000
    mov     r4, #0
clr:
    mov     r0, #0
    add     r3, r9, r4, lsl #1
    strh    r0, [r3]
    add     r4, r4, #1
    ldr     r1, =38400
    cmp     r4, r1
    bne     clr

    @ ---- squares 0..10: plain byte loads at increasing offsets
    mov     r8, #0                  @ index
b_loop:
    ldr     r4, =0x08000000 + DATA
    add     r4, r4, r8
    ldrb    r0, [r4]                @ what the CPU reads
    ldr     r5, =0x03E0
    @ expected: DATA[i] == 0xA0 + i (see the table below)
    add     r1, r8, #0xA0
    cmp     r0, r1
    movne   r5, #0
    ldrne   r5, =0x001F
    mov     r0, r8
    mov     r1, #16
    mul     r0, r1, r0
    mov     r4, #0
    bl      square
    add     r8, r8, #1
    cmp     r8, #11
    bne     b_loop

    @ ---- squares 11..14: byte loads from a base that is NOT word aligned,
    @ which is the access pattern a font decoder uses.
    mov     r8, #0
bo_loop:
    ldr     r4, =0x08000000 + ODDBASE + 3
    add     r4, r4, r8
    ldrb    r0, [r4]
    ldr     r5, =0x03E0
    add     r1, r8, #0x40
    cmp     r0, r1
    movne   r5, #0
    ldrne   r5, =0x001F
    add     r0, r8, #11
    mov     r1, #16
    mul     r0, r1, r0
    mov     r4, #0
    bl      square
    add     r8, r8, #1
    cmp     r8, #4
    bne     bo_loop

    ldr     r11, =0x04000000
    ldr     r0, =0x0403
    strh    r0, [r11]
h:  b       h

square:
    mov     r10, r4
sq_y:
    mov     r3, #0
sq_x:
    mov     r1, #240
    mul     r2, r1, r10
    add     r2, r2, r0
    add     r2, r2, r3
    add     r2, r9, r2, lsl #1
    strh    r5, [r2]
    add     r3, r3, #1
    cmp     r3, #16
    bne     sq_x
    add     r10, r10, #1
    mov     r1, r10
    sub     r1, r1, r4
    cmp     r1, #16
    bne     sq_y
    bx      lr

    .ltorg
    .align 4
DATA:
    .byte 0xA0,0xA1,0xA2,0xA3,0xA4,0xA5,0xA6,0xA7,0xA8,0xA9,0xAA
ODDBASE:
    .byte 0x00,0x00,0x00
    .byte 0x40,0x41,0x42,0x43
    .byte 0x00,0x00
