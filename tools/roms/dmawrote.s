@ Did the DMA write anything at all, and was it the right data?
@
@ The earlier DMA probes only compared the destination against the expected
@ pattern, so "not written" and "written with the wrong data" both read as red.
@ minidma compares against 0x0000, so a transfer that writes zeros would pass it
@ while failing a probe that expects a non-zero pattern -- which would explain
@ why those two disagreed on the same board. This probe separates the cases.
@
@ Destination pre-filled with 0xBBBBBBBB, pattern word 0 is 0x11111111.
@   0  green: the destination CHANGED  -> the DMA wrote something
@   1  green: the destination is 0x11111111 -> the DMA wrote the right data
@   2  green: the destination is exactly ZERO (the transfer wrote nothing useful)
@   3  yellow: reached the end
@ 0 red is "nothing written".  0 green + 1 red is "written, but not the pattern".

_start:
    ldr     r11, =0x04000000
    mov     r0, #0
    strh    r0, [r11]
    ldr     r0, =0x0403
    strh    r0, [r11]

    ldr     r9, =0x06000000
    mov     r4, #0
clr:
    ldr     r0, =0x7C00
    add     r3, r9, r4, lsl #1
    strh    r0, [r3]
    add     r4, r4, #1
    ldr     r1, =38400
    cmp     r4, r1
    bne     clr

    ldr     r0, =0x03001000
    ldr     r1, =0xBBBBBBBB
    str     r1, [r0]

    ldr     r0, =0x040000D4
    ldr     r1, =0x08000000 + PAT
    str     r1, [r0]
    ldr     r1, =0x03001000
    str     r1, [r0, #4]
    ldr     r1, =0x8400003F
    str     r1, [r0, #8]

    ldr     r2, =2048
st: subs    r2, r2, #1
    bne     st

    ldr     r0, =0x03001000
    ldr     r8, [r0]                @ what the destination holds now

    @ ---- 0: did it change at all?
    ldr     r1, =0xBBBBBBBB
    ldr     r5, =0x001F
    cmp     r8, r1
    ldrne   r5, =0x03E0
    mov     r0, #0
    mov     r4, #0
    bl      draw

    @ ---- 1: is it the pattern?
    ldr     r1, =0x11111111
    ldr     r5, =0x001F
    cmp     r8, r1
    ldreq   r5, =0x03E0
    mov     r0, #16
    mov     r4, #0
    bl      draw

    @ ---- 2: is it exactly zero?
    mov     r5, #0x001F
    cmp     r8, #0
    ldreq   r5, =0x03E0
    mov     r0, #32
    mov     r4, #0
    bl      draw

    @ ---- 3: reached the end
    ldr     r5, =0x03FF
    mov     r0, #48
    mov     r4, #0
    bl      draw

h:  b       h

draw:
    ldr     r9, =0x06000000
    mov     r10, r4
sq_y:
    mov     r3, #0
sq_x:
    mov     r1, #240
    mul     r2, r1, r10
    add     r2, r2, r0
    add     r2, r2, r3
    add     r2, r9, r2, lsl #1
    strh    r5, [r2]
    add     r3, r3, #1
    cmp     r3, #16
    bne     sq_x
    add     r10, r10, #1
    mov     r1, r10
    sub     r1, r1, r4
    cmp     r1, #16
    bne     sq_y
    bx      lr

    .ltorg

