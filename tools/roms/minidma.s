_start:
    ldr     r11, =0x04000000
    mov     r0, #0
    strh    r0, [r11]
    ldr     r0, =0x0403
    strh    r0, [r11]

    ldr     r9, =0x06000000
    @ paint whole screen from a CPU loop first, so any DMA result is obvious
    mov     r4, #0
clr:
    ldr     r0, =0x001F
    add     r3, r9, r4, lsl #1
    strh    r0, [r3]
    add     r4, r4, #1
    ldr     r1, =38400
    cmp     r4, r1
    bne     clr

    @ --- DMA3 fill: one constant word replicated 240 times to 0x06000000
    ldr     r0, =0x040000D4
    ldr     r1, =0x08000000 + SRC
    str     r1, [r0]
    ldr     r1, =0x06000000
    str     r1, [r0, #4]
    ldr     r1, =0x8400003F         @ enable|32bit|src INC|dst inc, 64 words
    str     r1, [r0, #8]

    @ settle
    mov     r2, #256
st:
    subs    r2, r2, #1
    bne     st

    @ read back halfword 0 and compare with the low half of SRC
    @ Classify the first halfword of the destination:
    @   0x0000  -> green  (DMA copied ROM word 0, whose low half is 0)
    @   0x001F  -> red    (still the clear value: DMA did not run)
    @   other   -> blue   (something landed, but not the expected value)
    ldr     r3, =0x06000000
    ldrh    r0, [r3]
    mov     r6, #2                  @ blue by default
    cmp     r0, #0
    moveq   r6, #0                  @ green
    ldr     r1, =0x001F
    cmp     r0, r1
    moveq   r6, #1                  @ red

    @ draw: full screen green if match, upper half only if mismatch
    mov     r4, #0
draw:
    cmp     r6, #0
    beq     dgreen
    cmp     r6, #1
    beq     dred
    ldr     r5, =0x7C00             @ blue: other value
    b       dput
dgreen:
    ldr     r5, =0x03E0
    b       dput
dred:
    ldr     r5, =0x001F
dput:
    mov     r3, #0
dp:
    mov     r1, #240
    mul     r2, r1, r4
    add     r2, r2, r3
    add     r2, r9, r2, lsl #1
    strh    r5, [r2]
    add     r3, r3, #1
    cmp     r3, #240
    bne     dp
    add     r4, r4, #1
    cmp     r4, #160
    bne     draw

    ldr     r11, =0x04000000
    ldr     r0, =0x0403
    strh    r0, [r11]
h:  b       h

    .ltorg
    .align 4
SRC:
    .rept   64
    .word   0x12340000 + (. - SRC) / 4
    .endr
