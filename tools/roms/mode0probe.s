@ Mode 0 text background, which no probe has used.  Every earlier probe draws in
@ mode 3 bitmap, but the RetroRegen cartridge's menu is a tiled background, so
@ if mode 0 is broken the menu can never appear and only anything drawn in
@ bitmap mode would show -- which is roughly the shape of the failure.
@
@ Layout: char base block 0 -> tiles at 0x06000000; screen base block 28 ->
@ map at 0x0600E000.  Tile 1 is filled with colour index 1; palette entry 1 is
@ green.  The whole 32x32 map is tile 1, so a working mode 0 fills the screen.
@   green   mode 0 displays the background
@   black   it does not
_start:
    ldr     r11, =0x04000000
    mov     r0, #0
    strh    r0, [r11]               @ forced blank

    @ palette: BG entry 1 = green 0x03E0
    ldr     r0, =0x05000000
    ldr     r1, =0x03E0
    strh    r1, [r0, #2]            @ entry 1

    @ tile 1: 32 bytes of 0x11 (two pixels of index 1 per byte), at +32
    ldr     r0, =0x06000000
    ldr     r1, =0x11111111
    add     r2, r0, #32
    mov     r3, #8
tile:
    str     r1, [r2], #4
    subs    r3, r3, #1
    bne     tile

    @ map: 32x32 entries of tile 1 at 0x0600E000
    ldr     r2, =0x0600E000
    ldr     r1, =0x0001
    mov     r3, #0
    ldr     r4, =1024
map:
    strh    r1, [r2], #2
    add     r3, r3, #1
    cmp     r3, r4
    bne     map

    @ BG0CNT: screen base 28, char base 0, 4bpp, priority 0
    ldr     r0, =0x04000008
    ldr     r1, =0x1C00
    strh    r1, [r0]

    @ DISPCNT = mode 0 | BG0 on
    ldr     r11, =0x04000000
    ldr     r0, =0x0100
    strh    r0, [r11]
h:  b       h
