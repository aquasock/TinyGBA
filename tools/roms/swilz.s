@ Does the BIOS LZ77 decompression work?
@
@ Every GBA title decompresses its fonts, tiles and palettes with a BIOS SWI:
@ 0x11 LZ77UnCompWram, 0x12 LZ77UnCompVram, 0x13 HuffmanUnComp.  The diag
@ cartridge draws its text at the correct position, colour and size but with
@ wrong glyph bitmaps (BRD-054), which is exactly what decompressing the font
@ incorrectly would look like: the layout code is the cartridge's own and works,
@ while the font data it decompressed is garbage.
@
@ SWI 0x11 takes r0 = source, r1 = destination.  The source below is an LZ77
@ stream of pure literals for a 32-byte pattern, so the expected output is known
@ exactly and no compressor is needed to check it.
@
@   0  green: LZ77 to IWRAM (SWI 0x11) produced the expected 32 bytes
@   1  yellow: reached the end

_start:
    ldr     r11, =0x04000000
    mov     r0, #0
    strh    r0, [r11]
    ldr     r0, =0x0403
    strh    r0, [r11]

    ldr     r9, =0x06000000
    mov     r4, #0
clr:
    ldr     r0, =0x7C00
    add     r3, r9, r4, lsl #1
    strh    r0, [r3]
    add     r4, r4, #1
    ldr     r1, =38400
    cmp     r4, r1
    bne     clr

    @ poison the destination so a no-op cannot pass
    ldr     r0, =0x03001000
    ldr     r1, =0xFFFFFFFF
    str     r1, [r0]
    str     r1, [r0, #4]
    str     r1, [r0, #8]
    str     r1, [r0, #12]
    str     r1, [r0, #16]
    str     r1, [r0, #20]
    str     r1, [r0, #24]
    str     r1, [r0, #28]

    adr     r0, lzsrc
    ldr     r1, =0x03001000
    swi     0x110000                @ LZ77UnCompWram

    @ compare 32 bytes against the pattern
    adr     r8, expect
    ldr     r10, =0x03001000
    mov     r6, #0
    mov     r2, #0
cmp_:
    ldr     r3, [r10, r2, lsl #2]
    ldr     r1, [r8, r2, lsl #2]
    cmp     r3, r1
    addne   r6, r6, #1
    add     r2, r2, #1
    cmp     r2, #8
    bne     cmp_

    ldr     r5, =0x001F
    cmp     r6, #0
    ldreq   r5, =0x03E0
    ldr     r9, =0x06000000
    mov     r0, #0
    mov     r4, #0
    bl      square

    ldr     r5, =0x03FF
    mov     r0, #16
    mov     r4, #0
    bl      square
h:  b       h

square:
    ldr     r9, =0x06000000
    mov     r10, r4
sq_y:
    mov     r3, #0
sq_x:
    mov     r1, #240
    mul     r2, r1, r10
    add     r2, r2, r0
    add     r2, r2, r3
    add     r2, r9, r2, lsl #1
    strh    r5, [r2]
    add     r3, r3, #1
    cmp     r3, #16
    bne     sq_x
    add     r10, r10, #1
    mov     r1, r10
    sub     r1, r1, r4
    cmp     r1, #16
    bne     sq_y
    bx      lr

    .ltorg

    .align  2
