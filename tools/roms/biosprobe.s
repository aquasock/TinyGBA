@ Which BIOS is actually resident?  The first instruction word differs between the
@ two candidates this project uses:
@   official                    0xEA000018
@   Cult-of-GBA (vendored)      0xEA000006
@ The RetroRegen cartridge labels itself "AGB BIOS", so a cart that inspects the
@ BIOS could behave differently under one than the other, which is worth knowing
@ before another probe is written.
@   green   word 0x00000000 == 0xEA000018  (official)
@   red     word 0x00000000 == 0xEA000006  (Cult-of-GBA)
@   blue    anything else
_start:
    ldr     r11, =0x04000000
    mov     r0, #0
    strh    r0, [r11]
    ldr     r0, =0x0403
    strh    r0, [r11]

    ldr     r9, =0x06000000
    ldr     r3, =0x00000000
    ldr     r0, [r3]
    ldr     r5, =0x7C00             @ blue: unrecognised
    ldr     r1, =0xEA000018
    cmp     r0, r1
    ldreq   r5, =0x03E0             @ green
    ldr     r1, =0xEA000006
    cmp     r0, r1
    ldreq   r5, =0x001F             @ red

    @ lower half of the screen carries the colour; upper half shows the word's
    @ low byte as a bar length, so an unrecognised BIOS can still be identified.
    mov     r4, #0
pt:
    mov     r3, #0
ptx:
    mov     r1, #240
    mul     r2, r1, r4
    add     r2, r2, r3
    add     r2, r9, r2, lsl #1
    cmp     r4, #80
    strhsh  r5, [r2]
    bhs     pnext
    ldr     r6, [r11]               @ unused, keeps the branch simple
    and     r0, r0, r0
pnext:
    add     r3, r3, #1
    cmp     r3, #240
    bne     ptx
    add     r4, r4, #1
    cmp     r4, #160
    bne     pt

    ldr     r11, =0x04000000
    ldr     r0, =0x0403
    strh    r0, [r11]
h:  b       h
